  select 1 from public.servers s
  where s.id::text = (storage.foldername(name))[1] and s.owner_id = auth.uid()
));
drop policy if exists "server_files_storage_update" on storage.objects;
create policy "server_files_storage_update" on storage.objects for update to authenticated
using (bucket_id = 'server-files' and exists (
  select 1 from public.servers s
  where s.id::text = (storage.foldername(name))[1] and s.owner_id = auth.uid()
))
with check (bucket_id = 'server-files' and exists (
  select 1 from public.servers s
  where s.id::text = (storage.foldername(name))[1] and s.owner_id = auth.uid()
));
drop policy if exists "server_files_storage_delete" on storage.objects;
create policy "server_files_storage_delete" on storage.objects for delete to authenticated
using (bucket_id = 'server-files' and exists (
  select 1 from public.servers s
  where s.id::text = (storage.foldername(name))[1] and s.owner_id = auth.uid()
