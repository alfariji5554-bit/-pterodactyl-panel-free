-- Jalankan di Supabase SQL Editor untuk tabel, RLS, dan bucket private.
create extension if not exists pgcrypto;

create table if not exists public.servers (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  status text not null default 'offline',
  memory_mb integer not null default 1024,
  disk_mb integer not null default 5120,
  cpu_percent numeric not null default 100,
  startup_command text not null default 'node index.js',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.servers add column if not exists startup_command text not null default 'node index.js';
alter table public.servers add column if not exists updated_at timestamptz not null default now();

create table if not exists public.server_files (
  id bigint generated by default as identity primary key,
  server_id uuid not null references public.servers(id) on delete cascade,
  path text not null,
  name text not null,
  is_directory boolean not null default false,
  size_bytes bigint not null default 0,
  storage_path text,
  created_at timestamptz not null default now(),
  unique (server_id, path)
);

alter table public.server_files add column if not exists storage_path text;
alter table public.server_files enable row level security;
alter table public.servers enable row level security;

drop policy if exists "servers_owner_select" on public.servers;
create policy "servers_owner_select" on public.servers for select to authenticated using (owner_id = auth.uid());
drop policy if exists "servers_owner_insert" on public.servers;
create policy "servers_owner_insert" on public.servers for insert to authenticated with check (owner_id = auth.uid());
drop policy if exists "servers_owner_update" on public.servers;
create policy "servers_owner_update" on public.servers for update to authenticated using (owner_id = auth.uid()) with check (owner_id = auth.uid());
drop policy if exists "servers_owner_delete" on public.servers;
create policy "servers_owner_delete" on public.servers for delete to authenticated using (owner_id = auth.uid());

drop policy if exists "server_files_owner_select" on public.server_files;
create policy "server_files_owner_select" on public.server_files for select to authenticated
using (exists (select 1 from public.servers s where s.id = server_files.server_id and s.owner_id = auth.uid()));
drop policy if exists "server_files_owner_insert" on public.server_files;
create policy "server_files_owner_insert" on public.server_files for insert to authenticated
with check (exists (select 1 from public.servers s where s.id = server_files.server_id and s.owner_id = auth.uid()));
drop policy if exists "server_files_owner_update" on public.server_files;
create policy "server_files_owner_update" on public.server_files for update to authenticated
using (exists (select 1 from public.servers s where s.id = server_files.server_id and s.owner_id = auth.uid()))
with check (exists (select 1 from public.servers s where s.id = server_files.server_id and s.owner_id = auth.uid()));
drop policy if exists "server_files_owner_delete" on public.server_files;
create policy "server_files_owner_delete" on public.server_files for delete to authenticated
using (exists (select 1 from public.servers s where s.id = server_files.server_id and s.owner_id = auth.uid()));

insert into storage.buckets (id, name, public, file_size_limit)
values ('server-files', 'server-files', false, 20971520)
on conflict (id) do update set public = false, file_size_limit = 20971520;

drop policy if exists "server_files_storage_select" on storage.objects;
create policy "server_files_storage_select" on storage.objects for select to authenticated
using (bucket_id = 'server-files' and exists (
  select 1 from public.servers s
  where s.id::text = (storage.foldername(name))[1] and s.owner_id = auth.uid()
));
drop policy if exists "server_files_storage_insert" on storage.objects;
